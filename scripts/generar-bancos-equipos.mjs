const ensayoHtml = (fase, fam, codigo, n, e) => {
  const id = `EQ-${fase}-${codigo}-${String(n).padStart(3, '0')}`;
  const pasos = e.p.map((p, i) => `${i + 1}) ${esc(p)}`);
  if (e.a) pasos.push(`${pasos.length + 1}) Procesar los datos crudos de este ensayo en el módulo de análisis estadístico y anexar la data cruda y el reporte generado como evidencia`);
  const entregables = e.e.slice();
  if (e.a) entregables.push('Data cruda y reporte estadístico del análisis correspondiente');
  return `  <article data-bloque="3" id="art-${id}" class="ensayo" data-id="${id}" data-fase="${fase}" data-cond="ambas" data-familia="${fam}"${e.a ? ' data-analisis="si"' : ''}>
  <h3>${id} — ${esc(e.t)}</h3>
  <p><strong>Objetivo:</strong><br>${esc(e.o)}</p>
  <p><strong>Procedimiento:</strong><br>
  ${pasos.join('<br>\n  ')}</p>
${e.a ? `  <p><strong>Plan estadístico:</strong><br>${PLAN}</p>\n` : ''}  <p><strong>Criterio de aceptación:</strong><br>
  ${e.c.map(esc).join('<br>\n  ')}</p>
  <p><strong>Documentos entregables:</strong><br>
  ${entregables.map((x) => '- ' + esc(x)).join('<br>\n  ')}</p>
  <p><strong>Referencia:</strong><br>${esc(e.r)}</p>
  </article>`;
};

